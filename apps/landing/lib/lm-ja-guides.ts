/** /lm link with UTM tags so every guide click is attributable. */
export function lmHref(campaign: string, content: string): string {
  const p = new URLSearchParams({
    lang: 'ja',
    utm_source: 'aniccaai',
    utm_medium: 'seo',
    utm_campaign: campaign,
    utm_content: content,
  });
  return `/lm?${p.toString()}`;
}

