export const JA_AFFIRMATION_APP_STORE_BASE =
  'https://apps.apple.com/jp/app/id6755129214';

export function jaAffirmationAppStoreUrl(slug: string): string {
  const url = new URL(JA_AFFIRMATION_APP_STORE_BASE);
  url.searchParams.set('utm_source', 'aniccaai');
  url.searchParams.set('utm_medium', 'seo');
  url.searchParams.set('utm_campaign', 'anicca_ja_problem');
  url.searchParams.set('utm_content', slug);
  url.searchParams.set('pt', '93486075');
  url.searchParams.set('ct', `seo_ja_${slug}`.slice(0, 40));
  url.searchParams.set('mt', '8');
  return url.toString();
}

