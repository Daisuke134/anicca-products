function requestHeaders(event) {
  return Object.fromEntries(Object.entries(event?.headers || {}).map(([key, value]) => [key.toLowerCase(), value]));
}

function isCapafyUrl(value) {
  try {
    const url = new URL(value);
    return url.protocol === 'https:'
      && !url.username
      && !url.password
      && !url.port
      && (url.hostname === 'capafy.ai' || url.hostname.endsWith('.capafy.ai'));
  } catch {
    return false;
  }
}

function normalizeCapafyUrl(value) {
  if (!isCapafyUrl(value)) return null;
  const url = new URL(value);
  url.hash = '';
  return url.href;
}

function isValidConsumedCost(value, budgetMicroUsd) {
  return Number.isFinite(value)
    && value >= 0
    && Number.isFinite(budgetMicroUsd)
    && budgetMicroUsd >= 0
    && value <= budgetMicroUsd;
}

function validateReport(value) {
  if (!value || typeof value !== 'object') return false;
  if (typeof value.product !== 'string' || typeof value.summary !== 'string' || value.summary.trim().length < 20) return false;
  if (!Array.isArray(value.findings) || value.findings.length < 1 || value.findings.length > 5) return false;
  if (!Array.isArray(value.limitations) || value.limitations.some((item) => typeof item !== 'string')) return false;
  return value.findings.every((finding) => (
    finding
    && typeof finding.title === 'string'
    && finding.title.trim().length > 0
    && typeof finding.observation === 'string'
    && finding.observation.trim().length > 0
    && isCapafyUrl(finding.source_url)
  ));
}

function collectBrowserEvidence(events) {
  if (!Array.isArray(events)) return null;
  const ordered = [...events].sort((a, b) => a.seq - b.seq);
  const started = new Map();
  const opened = new Set();
  const closed = new Set();
  const observedSourceUrls = new Set();
  let currentPageUrl = null;

  for (const event of ordered) {
    const data = event?.data || {};
    if (
      event?.type === 'browser.session.opened'
      && typeof data.browser_session_id === 'string'
      && data.browser_session_id
    ) {
      opened.add(data.browser_session_id);
      continue;
    }
    if (event?.type === 'browser.session.closed' && typeof data.browser_session_id === 'string' && data.browser_session_id) {
      closed.add(data.browser_session_id);
      continue;
    }
    if (event?.type === 'tool.started' && data.name === 'browser' && data.tool_call_id) {
      const args = data.args || {};
      if (['goto', 'click', 'act'].includes(args.action)) currentPageUrl = null;
      started.set(data.tool_call_id, args);
      continue;
    }
    if (event?.type !== 'tool.completed' || data.name !== 'browser') continue;

    const args = started.get(data.tool_call_id);
    started.delete(data.tool_call_id);
    const outputIsPresent = typeof data.output === 'string' && data.output.trim().length > 0;
    if (!args || data.is_error !== false || !outputIsPresent) continue;

    if (args.action === 'goto') {
      const requestedUrl = normalizeCapafyUrl(args.url);
      const landedUrl = normalizeCapafyUrl(data.output.trim());
      currentPageUrl = requestedUrl && landedUrl === requestedUrl ? landedUrl : null;
    } else if (['observe', 'extract'].includes(args.action) && currentPageUrl) {
      observedSourceUrls.add(currentPageUrl);
    } else if (['click', 'act'].includes(args.action)) {
      currentPageUrl = null;
    }
  }

  const browserSessionId = [...opened].find((id) => closed.has(id));
  if (!browserSessionId || observedSourceUrls.size === 0) return null;
  return { browserSessionId, observedSourceUrls: [...observedSourceUrls] };
}

function validateBrowserEvidence(events, findings) {
  const evidence = collectBrowserEvidence(events);
  if (!evidence || !Array.isArray(findings) || findings.length === 0) return false;
  const observed = new Set(evidence.observedSourceUrls);
  return findings.every((finding) => {
    const sourceUrl = normalizeCapafyUrl(finding?.source_url);
    return sourceUrl !== null && observed.has(sourceUrl);
  });
}

function sourcesAreObserved(findings, observedSourceUrls) {
  if (!Array.isArray(observedSourceUrls)) return false;
  const observed = new Set(observedSourceUrls.map(normalizeCapafyUrl).filter(Boolean));
  return Array.isArray(findings)
    && findings.length > 0
    && findings.every((finding) => {
      const sourceUrl = normalizeCapafyUrl(finding?.source_url);
      return sourceUrl !== null && observed.has(sourceUrl);
    });
}

function newNaiveClient() {
  const apiKey = process.env.NAIVE_VETTA_API_KEY;
  if (!apiKey || !AGENT_ID) throw new Error('naive_configuration_missing');
  return import('@usenaive-sdk/vetta').then(({ createClient }) => createClient({
    baseUrl: 'https://api.vetta.sh',
    apiKey,
    fetch: globalThis.fetch,
    idempotencyKey: () => crypto.randomUUID(),
  }));
}

function hasSafeNaiveTools(agent) {
  const configs = agent.tools.configs;
  const enabledTools = Object.entries(configs).filter(([, settings]) => settings.enabled).map(([name]) => name);
  const browser = configs.browser;
  const browserConfig = browser?.config || {};
  const allowedDomains = browserConfig.allowed_domains || [];
  return agent.tools.default_config.permission === 'deny'
    && enabledTools.length === 2
    && enabledTools.includes('browser')
    && enabledTools.includes('ls')
    && browser?.permission === 'allow'
    && configs.ls?.permission === 'allow'
    && allowedDomains.includes('capafy.ai')
    && allowedDomains.includes('*.capafy.ai')
    && browserConfig.allow_writes === false
    && browserConfig.solve_captchas === false
    && browserConfig.persist_context === false
    && browserConfig.human_login === false
    && browserConfig.proxy === false;
}

async function runNaiveReport({ paymentHeader, requestId }) {
  const client = await newNaiveClient();
  const agent = await client.agents.get(AGENT_ID);
  if (!hasSafeNaiveTools(agent)) throw new Error('naive_agent_safety_config_mismatch');

  const requestHash = crypto.createHash('sha256').update(paymentHeader).digest('hex');
  const session = await client.sessions.create({
    agent_id: AGENT_ID,
    message: 'Create one concise, source-linked snapshot of Capafy’s public agent marketplace. First use the read-only ls tool once on /home/tenki, the Computer home returned by inspect, to list names only; do not open files. Do not use shell or any other filesystem tool. Then use only the Naive-managed cloud browser to open https://capafy.ai/ and inspect the visible homepage. Return at most two factual findings with exact Capafy URLs you opened. State only visible observations; do not estimate or claim earnings, sales, rankings, or totals. If you cannot access the public page or evidence is insufficient, explain the limitation and do not invent findings. Do not sign up, log in, submit forms, publish, purchase, message, solve CAPTCHA, or use personal credentials.',
    window: 'immediate',
    budget_micro_usd: SESSION_BUDGET_MICRO_USD,
    output_schema: REPORT_SCHEMA,
    structured_output_required: true,
    metadata: { product: 'capafy-public-market-report', request_id: String(requestId || '').slice(0, 100) },
  }, { idempotencyKey: `capafy-report-${requestHash}` });

  const deadline = Date.now() + WAIT_LIMIT_MS;
  let finalSession = session;
  while (Date.now() < deadline) {
    finalSession = await client.sessions.get(session.id);
    if (['completed', 'idle', 'failed', 'cancelled'].includes(finalSession.status)) break;
    await new Promise((resolve) => setTimeout(resolve, POLL_INTERVAL_MS));
  }
  if (!['completed', 'idle', 'failed', 'cancelled'].includes(finalSession.status)) {
    try { await client.sessions.interrupt(session.id); } catch { /* bounded session budget remains the backstop */ }
    throw new Error('naive_session_timeout');
  }
  if (
    !['completed', 'idle'].includes(finalSession.status)
    || finalSession.stop_reason !== 'end_turn'
    || typeof finalSession.computer_id !== 'string'
    || !finalSession.computer_id
  ) {
    throw new Error('naive_session_not_successful');
  }
  if (!isValidConsumedCost(finalSession.consumed_micro_usd, SESSION_BUDGET_MICRO_USD) || !validateReport(finalSession.structured_output)) {
    throw new Error('naive_report_invalid');
  }

  const events = await client.sessions.events(session.id, { limit: 100 });
  const browserEvidence = collectBrowserEvidence(events.data);
  if (
    events.has_more
    || !browserEvidence
    || !validateBrowserEvidence(events.data, finalSession.structured_output.findings)
  ) {
    throw new Error('naive_browser_evidence_missing');
  }

  return {
    sessionId: finalSession.id,
    computerId: finalSession.computer_id,
    browserSessionId: browserEvidence.browserSessionId,
    report: finalSession.structured_output,
    observedSourceUrls: browserEvidence.observedSourceUrls,
  };
}

function createHandler(runAgent = runNaiveReport) {
  const paidHandler = seller(async (_query, event) => {
    const headers = requestHeaders(event);
    const paymentHeader = headers['payment-signature'] || headers['x-payment'];
    const requestId = headers['x-nf-request-id'] || headers['x-request-id'] || '';
    try {
      const result = await runAgent({ paymentHeader, requestId });
      if (
        !result?.sessionId
        || !result.computerId
        || !result.browserSessionId
        || !validateReport(result.report)
        || !sourcesAreObserved(result.report.findings, result.observedSourceUrls)
      ) return { status: 502, body: { error: 'report_unavailable' } };
      return {
        status: 200,
        body: {
          ...result.report,
          generated_at: new Date().toISOString(),
          agent_session_id: result.sessionId,
          agent_computer_id: result.computerId,
          agent_browser_session_id: result.browserSessionId,
        },
      };
    } catch {
      return { status: 503, body: { error: 'report_unavailable', request_id: requestId || undefined } };
    }
  });

  return async (event) => {
    if (event.httpMethod === 'HEAD') return json(405, { error: 'GET only' });
    return paidHandler(event);
  };
}

