function assertType(type) {
  if (!TYPE_SET.has(type)) throw new TypeError('invalid type');
}

function parseScores(s) {
  if (typeof s !== 'string' || !/^[0-9]{8}$/.test(s)) return null;
  const scores = {};
  TYPE_ORDER.forEach((id, i) => {
    scores[id] = Number(s[i]);
  });
  return scores;
}

function rankTypes(scores) {
  return [...TYPE_ORDER].sort((a, b) => {
    if (scores[b] !== scores[a]) return scores[b] - scores[a];
    return TYPE_ORDER.indexOf(a) - TYPE_ORDER.indexOf(b);
  });
}

const { REPORTS_EN } = require('./kokoro-report-content-en.js');

function wallpaperUrl(text, bg, lang) {
  const u = new URL('https://aniccaai.com/affirmation-app/ja/wallpaper');
  u.searchParams.set('text', text);
  if (bg) u.searchParams.set('bg', bg);
  u.searchParams.set('from', lang === 'en' ? 'kokoro_report_en' : 'kokoro_report');
  return u.toString();
}

/**
 * @param {{ type: string, s?: string, lang?: string }} input
 */
