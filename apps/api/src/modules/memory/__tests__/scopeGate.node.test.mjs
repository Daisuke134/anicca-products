import test from 'node:test';
import assert from 'node:assert/strict';
import { filterScopedMemories } from '../scopeGate.js';
const now=100;
const grant={subjectId:'s',recipientId:'r',purpose:'delivery',expiresAt:200,allowedIds:['a','b'],revoked:false};
const a={id:'a',subjectId:'s',recipientId:'r',purpose:'delivery',expiresAt:200,revoked:false,content:'fictional'};
const check=(records,g=grant,t=now)=>filterScopedMemories(records,g,t).map(x=>x.id);
test('permitted record',()=>assert.deepEqual(check([a]),['a']));
test('wrong subject',()=>assert.deepEqual(check([{...a,subjectId:'other'}]),[]));
test('wrong recipient',()=>assert.deepEqual(check([{...a,recipientId:'other'}]),[]));
test('wrong purpose',()=>assert.deepEqual(check([{...a,purpose:'other'}]),[]));
test('unknown ID',()=>assert.deepEqual(check([{...a,id:'c'}]),[]));
test('expired record at boundary',()=>assert.deepEqual(check([{...a,expiresAt:100}]),[]));
test('revoked record',()=>assert.deepEqual(check([{...a,revoked:true}]),[]));
test('missing revocation flag',()=>assert.deepEqual(check([{...a,revoked:undefined}]),[]));
test('expired grant',()=>assert.deepEqual(check([a],{...grant,expiresAt:100}),[]));
test('revoked grant',()=>assert.deepEqual(check([a],{...grant,revoked:true}),[]));
test('missing grant',()=>assert.deepEqual(check([a],null),[]));
test('empty grant purpose',()=>assert.deepEqual(check([a],{...grant,purpose:''}),[]));
test('invalid timestamp',()=>assert.deepEqual(check([a],grant,NaN),[]));
test('duplicate record IDs fail closed',()=>assert.deepEqual(check([a,{...a,content:'different'}]),[]));
test('metadata cannot override trusted record fields',()=>assert.deepEqual(check([{...a,purpose:'other',metadata:{purpose:'delivery'}}]),[]));
test('recheck at dispatch expiry',()=>assert.deepEqual(check([a],grant,200),[]));
test('no mutation, allowed subset',()=>{const records=Object.freeze([Object.freeze(a),Object.freeze({...a,id:'c'})]);assert.deepEqual(check(records),['a']);assert.equal(records.length,2)});
